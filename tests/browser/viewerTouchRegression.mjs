import assert from 'node:assert/strict'
import { writeFileSync } from 'node:fs'

export async function checkViewerTouch({ call, evaluate, pause, waitFor }) {
  await call('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await call('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 })
  await pause(300)
  const position = () => evaluate('window.viewerState().camera.position.toArray()')
  const rotation = () => evaluate('window.viewerState().camera.rotation.y')
  const touch = (type, points) => call('Input.dispatchTouchEvent', { type, touchPoints: points.map(([id, x, y]) => ({ id, x, y })) })
  const centre = await evaluate(`(()=>{const r=document.querySelector('.viewer-joystick').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.viewer-options')).display"), 'none')
  assert.equal(await evaluate("document.querySelector('.viewer-help').getBoundingClientRect().height"), 0)
  assert.equal(await evaluate("document.querySelector('.viewer-title').getBoundingClientRect().height"), 0, 'title stays inside the closed menu')
  assert.equal(await evaluate("document.querySelector('.viewer-toolbar').getBoundingClientRect().width"), 44, 'only a corner hamburger occupies the toolbar')
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.viewer-status')).backgroundColor"), 'rgba(0, 0, 0, 0)', 'status has no console bar')
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.viewer-status')).color"), 'rgb(74, 222, 128)', 'status is green text')
  await evaluate("(()=>{const c=window.viewerState().camera;c.position.set(4,1.8,7);c.rotation.set(0,0,0);c.updateMatrixWorld()})()")
  await pause(150)
  await touch('touchStart', [[1, centre.x, centre.y]])
  await touch('touchMove', [[1, centre.x, centre.y - 35]])
  await pause(350)
  assert.ok((await position())[2] < 6.9, 'left thumb walks forward')
  const before = await rotation(), moving = await position()
  await touch('touchStart', [[1, centre.x, centre.y - 35], [2, 280, 400]])
  for (let i = 1; i <= 5; i++) {
    await touch('touchMove', [[1, centre.x, centre.y - 35], [2, 280 + i * 12, 400 - i * 3]])
    await pause(30)
  }
  assert.ok(await rotation() < before - .05, 'right finger turns while left thumb moves')
  assert.notDeepEqual(await position(), moving)
  await touch('touchEnd', [[1, centre.x, centre.y - 35]])
  await pause(100)
  const stopped = await position(), stillLooking = await rotation()
  await touch('touchMove', [[2, 365, 385]])
  await pause(200)
  assert.deepEqual(await position(), stopped, 'lifting only left thumb stops walking')
  assert.ok(await rotation() < stillLooking, 'lifting left thumb does not cancel right finger look')
  await touch('touchEnd', [])
  await touch('touchStart', [[1, centre.x + 30, centre.y]])
  await pause(200)
  assert.notDeepEqual(await position(), stopped, 'joystick strafes')
  await touch('touchCancel', [])
  await pause(100)
  const cancelled = await position()
  await pause(250)
  assert.deepEqual(await position(), cancelled, 'cancelling a touch stops movement')
  await touch('touchStart', [[1, centre.x, centre.y - 35]])
  await pause(100)
  await evaluate("window.dispatchEvent(new Event('blur'))")
  await pause(100)
  const blurred = await position()
  await pause(200)
  assert.deepEqual(await position(), blurred, 'losing focus clears thumb input')
  await touch('touchEnd', [])
  const layout = () => evaluate(`(()=>{const selectors=['.viewer-toolbar','.viewer-joystick','.viewer-status'];const canvas=document.querySelector('canvas').getBoundingClientRect();return canvas.top===0&&Math.abs(canvas.height-visualViewport.height)<2&&selectors.every(s=>{const r=document.querySelector(s).getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight})&&document.documentElement.scrollWidth<=innerWidth})()`)
  assert.ok(await layout(), 'portrait controls stay inside the screen')
  writeFileSync('node_modules/.cache/viewer-phone-portrait.png', Buffer.from((await call('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await evaluate("document.querySelector('.viewer-menu-toggle').click()")
  await waitFor("getComputedStyle(document.querySelector('.viewer-options')).display==='flex'", 'mobile menu opens')
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.viewer-options')).display"), 'flex')
  await evaluate("[...document.querySelectorAll('.viewer-floor-controls button')].find(b=>b.textContent==='Upstairs').click()")
  await waitFor('window.viewerState().camera.position.y===4.5', 'mobile floor navigation')
  assert.equal((await position())[1], 4.5, 'floor controls work from the mobile menu')
  const fullscreenButton = await evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent==='Full screen');const r=b.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
  await call('Input.dispatchMouseEvent', { type: 'mousePressed', ...fullscreenButton, button: 'left', clickCount: 1 })
  await call('Input.dispatchMouseEvent', { type: 'mouseReleased', ...fullscreenButton, button: 'left', clickCount: 1 })
  await waitFor("document.fullscreenElement?.matches('.house-viewer')", 'tour enters full screen')
  assert.equal(await evaluate("document.fullscreenElement.contains(document.querySelector('.viewer-joystick'))"), true, 'full screen includes touch controls')
  await evaluate('document.exitFullscreen()')
  await waitFor("[...document.querySelectorAll('button')].some(b=>b.textContent==='Full screen'&&b.getAttribute('aria-pressed')==='false')", 'full-screen button tracks browser exit')
  await evaluate("Object.defineProperty(document,'fullscreenEnabled',{configurable:true,value:false});[...document.querySelectorAll('button')].find(b=>b.textContent==='Full screen').click()")
  await waitFor("document.querySelector('.viewer-fullscreen-help')?.textContent.includes('Add to Home Screen')", 'unsupported browsers get Home Screen instructions')
  await evaluate("delete document.fullscreenEnabled;document.querySelector('[aria-label=\"Dismiss full-screen instructions\"]').click()")
  await evaluate("document.querySelector('.viewer-menu-toggle').click()")
  await call('Emulation.setDeviceMetricsOverride', { width: 844, height: 390, deviceScaleFactor: 1, mobile: true })
  await pause(250)
  assert.ok(await layout(), 'landscape controls stay inside the screen')
  writeFileSync('node_modules/.cache/viewer-phone-landscape.png', Buffer.from((await call('Page.captureScreenshot', { format: 'png' })).data, 'base64'))
  await call('Emulation.clearDeviceMetricsOverride')
  await call('Emulation.setTouchEmulationEnabled', { enabled: false })
  console.log('PASS: Phone joystick, simultaneous touch look, independent release, cancellation, blur, menu, floors, full screen, Home Screen guidance and portrait/landscape layout.')
}
