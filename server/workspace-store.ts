import { DatabaseSync } from 'node:sqlite'
import { createHash, randomBytes, randomUUID, scrypt, timingSafeEqual } from 'node:crypto'
import { mkdir, readFile, unlink, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

export class WorkspaceError extends Error {
  status: number
  constructor(status: number, message: string) { super(message); this.status = status }
}

export type WorkspaceUser = { id: string; email: string; name: string }
export type PrivateAsset = {
  id: string; name: string; kind: 'material' | 'object' | 'project'; bytes: number
  contentType: string; createdAt: number; visibility: 'private'; sha256: string
}
type UserRow = WorkspaceUser & { password_hash: string; password_salt: string }
type AssetRow = {
  id: string; workspace_id: string; name: string; kind: PrivateAsset['kind']; byte_size: number
  content_type: string; created_at: number; sha256: string
  object_key?: string | null
}
const sessionHash = (token: string) => createHash('sha256').update(token).digest('hex')
const derivePassword = (password: string, salt: string) => new Promise<Buffer>((resolve, reject) => {
  scrypt(password, salt, 64, { N: 32768, r: 8, p: 1, maxmem: 64 * 1024 * 1024 },
    (error, key) => error ? reject(error) : resolve(key))
})
const publicUser = ({ id, email, name }: WorkspaceUser): WorkspaceUser => ({ id, email, name })
const publicAsset = (row: AssetRow): PrivateAsset => ({ id: row.id, name: row.name, kind: row.kind,
  bytes: row.byte_size, contentType: row.content_type, createdAt: row.created_at,
  visibility: 'private', sha256: row.sha256 })

/** All object keys are generated by the service. A future R2 adapter implements
 * this interface without exposing storage credentials to the editor. */
export interface WorkspaceObjects {
  put(workspaceId: string, assetId: string, contents: Uint8Array): Promise<void>
  get(workspaceId: string, assetId: string): Promise<Uint8Array>
  delete(workspaceId: string, assetId: string): Promise<void>
}

export function createLocalWorkspaceObjects(root: string): WorkspaceObjects {
  const objectPath = (workspaceId: string, assetId: string) => {
    if (![workspaceId, assetId].every(id => /^[a-f0-9-]{36}$/.test(id))) throw Error('Invalid internal object key')
    return join(root, workspaceId, assetId)
  }
  return {
    async put(workspaceId, assetId, contents) {
      const path = objectPath(workspaceId, assetId)
      await mkdir(dirname(path), { recursive: true })
      // The pending database row prevents reads until the write completes.
      // Use the tracked key even while writing, so recovery can remove a
      // partial file after process interruption without orphaned temp files.
      await writeFile(path, contents, { flag: 'wx', mode: 0o600, flush: true })
    },
    get: (workspaceId, assetId) => readFile(objectPath(workspaceId, assetId)),
    async delete(workspaceId, assetId) {
      await unlink(objectPath(workspaceId, assetId)).catch(error => { if (error.code !== 'ENOENT') throw error })
    },
  }
}

export async function createWorkspaceStore({ directory, quotaBytes = 100 * 1024 * 1024,
  sessionMilliseconds = 7 * 24 * 60 * 60 * 1000, now = Date.now, objects = createLocalWorkspaceObjects(join(directory, 'objects')),
}: { directory: string; quotaBytes?: number; sessionMilliseconds?: number; now?: () => number; objects?: WorkspaceObjects }) {
  if (!Number.isSafeInteger(quotaBytes) || quotaBytes <= 0) throw Error('Invalid workspace storage allowance')
  await mkdir(directory, { recursive: true, mode: 0o700 })
  const db = new DatabaseSync(join(directory, 'workspace.sqlite'))
  db.exec(`PRAGMA foreign_keys=ON; PRAGMA journal_mode=WAL; PRAGMA busy_timeout=5000;
    CREATE TABLE IF NOT EXISTS users (
      id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
      password_hash TEXT NOT NULL, password_salt TEXT NOT NULL, created_at INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS workspaces (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL UNIQUE REFERENCES users(id), quota_bytes INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), expires_at INTEGER NOT NULL
    );
    CREATE TABLE IF NOT EXISTS assets (
      id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), name TEXT NOT NULL,
      kind TEXT NOT NULL CHECK(kind IN ('material','object','project')), byte_size INTEGER NOT NULL,
      content_type TEXT NOT NULL, sha256 TEXT NOT NULL, created_at INTEGER NOT NULL,
      state TEXT NOT NULL CHECK(state IN ('pending','ready','deleting'))
    );
    CREATE INDEX IF NOT EXISTS assets_workspace ON assets(workspace_id);`)
  if (!(db.prepare('PRAGMA table_info(assets)').all() as { name: string }[]).some(column => column.name === 'object_key')) {
    db.exec('ALTER TABLE assets ADD COLUMN object_key TEXT')
  }
  // Incomplete uploads/deletions from an interrupted process never become
  // visible. Their reservations are reclaimed before the service accepts work.
  try {
    for (const row of db.prepare("SELECT id,workspace_id,object_key FROM assets WHERE state != 'ready'").all() as AssetRow[]) {
      await objects.delete(row.workspace_id, row.object_key ?? row.id)
      db.prepare('DELETE FROM assets WHERE id=?').run(row.id)
    }
  } catch (error) { db.close(); throw error }
  const transaction = <T>(operation: () => T): T => {
    db.exec('BEGIN IMMEDIATE')
    try { const result = operation(); db.exec('COMMIT'); return result }
    catch (error) { db.exec('ROLLBACK'); throw error }
  }
  const workspace = (userId: string) => {
    const row = db.prepare('SELECT id,quota_bytes FROM workspaces WHERE user_id=?').get(userId) as { id: string; quota_bytes: number } | undefined
    if (!row) throw new WorkspaceError(401, 'Sign in to use your workspace.')
    const usage = db.prepare('SELECT COALESCE(SUM(byte_size),0) AS bytes FROM assets WHERE workspace_id=?').get(row.id) as { bytes: number }
    return { id: row.id, quotaBytes: row.quota_bytes, usedBytes: usage.bytes }
  }
  const ownedAsset = (userId: string, id: string) => {
    const owner = workspace(userId)
    const row = db.prepare("SELECT * FROM assets WHERE id=? AND workspace_id=? AND state='ready'").get(id, owner.id) as AssetRow | undefined
    if (!row) throw new WorkspaceError(404, 'This file was not found in your workspace.')
    return row
  }
  const issueSession = (user: WorkspaceUser) => {
    const token = randomBytes(32).toString('base64url')
    const expiresAt = now() + sessionMilliseconds
    db.prepare('DELETE FROM sessions WHERE expires_at<=?').run(now())
    db.prepare('INSERT INTO sessions VALUES (?,?,?)').run(sessionHash(token), user.id, expiresAt)
    return { token, expiresAt, user: publicUser(user) }
  }
  const replacing = new Set<string>()
  return {
    close: () => db.close(), workspace,
    async register(input: { email?: unknown; name?: unknown; password?: unknown }) {
      const email = typeof input.email === 'string' ? input.email.trim().toLowerCase() : ''
      const name = typeof input.name === 'string' ? input.name.trim() : ''
      const password = typeof input.password === 'string' ? input.password : ''
      if (email.length > 254 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) throw new WorkspaceError(400, 'Enter a valid email address.')
      if (name.length < 2 || name.length > 80) throw new WorkspaceError(400, 'Enter a name between 2 and 80 characters.')
      if (password.length < 12 || password.length > 128) throw new WorkspaceError(400, 'Use a password between 12 and 128 characters.')
      const salt = randomBytes(16).toString('hex'), hash = (await derivePassword(password, salt)).toString('hex')
      const user = { id: randomUUID(), email, name }
      transaction(() => {
        if (db.prepare('SELECT id FROM users WHERE email=?').get(email)) throw new WorkspaceError(409, 'An account with this email already exists. Sign in instead.')
        db.prepare('INSERT INTO users VALUES (?,?,?,?,?,?)').run(user.id, email, name, hash, salt, now())
        db.prepare('INSERT INTO workspaces VALUES (?,?,?)').run(randomUUID(), user.id, quotaBytes)
      })
      return issueSession(user)
    },
    async login(input: { email?: unknown; password?: unknown }) {
      const email = typeof input.email === 'string' ? input.email.trim().toLowerCase().slice(0, 254) : ''
      const password = typeof input.password === 'string' && input.password.length <= 128 ? input.password : ''
      const user = db.prepare('SELECT * FROM users WHERE email=?').get(email) as UserRow | undefined
      const key = await derivePassword(password, user?.password_salt ?? '00000000000000000000000000000000')
      const expected = user ? Buffer.from(user.password_hash, 'hex') : Buffer.alloc(64)
      if (!user || !timingSafeEqual(key, expected)) throw new WorkspaceError(401, 'The email or password is incorrect.')
      return issueSession(user)
    },
    session(token: string) {
      if (!/^[A-Za-z0-9_-]{43}$/.test(token)) return null
      const row = db.prepare(`SELECT users.id,users.email,users.name FROM sessions JOIN users ON users.id=sessions.user_id
        WHERE token_hash=? AND expires_at>?`).get(sessionHash(token), now()) as WorkspaceUser | undefined
      return row ? publicUser(row) : null
    },
    logout: (token: string) => { db.prepare('DELETE FROM sessions WHERE token_hash=?').run(sessionHash(token)) },
    list(userId: string) {
      return (db.prepare("SELECT * FROM assets WHERE workspace_id=? AND state='ready' ORDER BY created_at DESC,id").all(workspace(userId).id) as AssetRow[]).map(publicAsset)
    },
    async upload(userId: string, input: { name: string; kind: PrivateAsset['kind']; contentType: string; contents: Uint8Array }) {
      const id = randomUUID(), { name, kind, contentType, contents } = input
      const owner = transaction(() => {
        const current = workspace(userId)
        if (current.usedBytes + contents.byteLength > current.quotaBytes) throw new WorkspaceError(413, 'This file would exceed your storage allowance.')
        db.prepare("INSERT INTO assets (id,workspace_id,name,kind,byte_size,content_type,sha256,created_at,state) VALUES (?,?,?,?,?,?,?,?, 'pending')").run(id, current.id, name, kind,
          contents.byteLength, contentType, createHash('sha256').update(contents).digest('hex'), now())
        return current
      })
      try {
        await objects.put(owner.id, id, contents)
        db.prepare("UPDATE assets SET state='ready' WHERE id=?").run(id)
      } catch (error) {
        // Keep the pending reservation if cleanup fails, so the bytes remain
        // accounted for and startup recovery can retry the deletion.
        await objects.delete(owner.id, id)
        db.prepare('DELETE FROM assets WHERE id=?').run(id)
        throw error
      }
      return publicAsset(ownedAsset(userId, id))
    },
    async replaceProject(userId: string, id: string, input: { name: string; kind: PrivateAsset['kind']; contentType: string; contents: Uint8Array }) {
      const previous = ownedAsset(userId, id)
      if (previous.kind !== 'project' || input.kind !== 'project') throw new WorkspaceError(400, 'Only house designs can be overwritten here.')
      if (replacing.has(id)) throw new WorkspaceError(409, 'This design is already being saved.')
      replacing.add(id)
      const key = randomUUID(), hash = createHash('sha256').update(input.contents).digest('hex')
      try {
        transaction(() => {
          const owner = workspace(userId), extra = Math.max(0, input.contents.byteLength - previous.byte_size)
          if (owner.usedBytes + extra > owner.quotaBytes) throw new WorkspaceError(413, 'This file would exceed your storage allowance.')
          db.prepare("INSERT INTO assets (id,workspace_id,name,kind,byte_size,content_type,sha256,created_at,state,object_key) VALUES (?,?,?,?,?,?,?,?,'pending',?)")
            .run(key, previous.workspace_id, input.name, 'project', extra, input.contentType, hash, now(), key)
        })
        try {
          await objects.put(previous.workspace_id, key, input.contents)
          transaction(() => {
            db.prepare('UPDATE assets SET name=?,byte_size=?,content_type=?,sha256=?,object_key=? WHERE id=?')
              .run(input.name, input.contents.byteLength, input.contentType, hash, key, id)
            // Track the superseded blob until deletion succeeds, including after
            // interruption. The logical design ID and download URL stay stable.
            db.prepare("UPDATE assets SET byte_size=0,state='deleting',object_key=? WHERE id=?").run(previous.object_key ?? id, key)
          })
        } catch (error) {
          await objects.delete(previous.workspace_id, key)
          db.prepare('DELETE FROM assets WHERE id=?').run(key)
          throw error
        }
        try {
          await objects.delete(previous.workspace_id, previous.object_key ?? id)
          db.prepare('DELETE FROM assets WHERE id=?').run(key)
        } catch { /* Startup recovery owns the tracked obsolete blob. */ }
        return publicAsset(ownedAsset(userId, id))
      } finally { replacing.delete(id) }
    },
    async download(userId: string, id: string) {
      const row = ownedAsset(userId, id)
      return { asset: publicAsset(row), contents: await objects.get(row.workspace_id, row.object_key ?? id) }
    },
    async remove(userId: string, id: string) {
      const row = ownedAsset(userId, id)
      if (replacing.has(id)) throw new WorkspaceError(409, 'This design is being saved.')
      db.prepare("UPDATE assets SET state='deleting' WHERE id=?").run(id)
      try { await objects.delete(row.workspace_id, row.object_key ?? id); db.prepare('DELETE FROM assets WHERE id=?').run(id) }
      catch (error) { db.prepare("UPDATE assets SET state='ready' WHERE id=?").run(id); throw error }
    },
  }
}

export type WorkspaceStore = Awaited<ReturnType<typeof createWorkspaceStore>>
